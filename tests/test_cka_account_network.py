"""Real disposable Docker proof of the account process's required network boundary."""
import os
import importlib.util
import json
import sys
import tempfile
from pathlib import Path
import secrets
import subprocess
import unittest

IMAGE='python:3.13-slim-bookworm@sha256:281d39ff02e3b389401586134ff9e6572954687822a58055ec07a60ded4e0b7f'
PROBE='''
import socket,time
from pathlib import Path
routes=[line.split() for line in Path('/proc/net/route').read_text().splitlines()[1:]]
assert not any(row[1]=='00000000' for row in routes), 'account has a default route'
for _ in range(30):
 try:
  with socket.create_connection(('id-staging.shadowops.dpdns.org',9443),timeout=1):pass
  break
 except OSError:time.sleep(.1)
else:raise AssertionError('private Identity alias not reachable')
for host,port in [('169.254.169.254',80),('1.1.1.1',443)]:
 try:
  connection=socket.create_connection((host,port),timeout=.3)
 except OSError:continue
 connection.close();raise AssertionError('off-network destination reachable')
print('CKA_PRIVATE_NETWORK_PROOF_OK')
'''

@unittest.skipUnless(os.environ.get('CKA_ACCOUNT_NETWORK_TEST')=='1','requires explicitly enabled disposable Docker networks')
class NetworkTests(unittest.TestCase):
    def test_actual_compose_normalization_matches_the_fixed_root_validator(self):
        root=Path(__file__).resolve().parents[1]
        sys.path.insert(0,str(root/'scripts'))
        spec=importlib.util.spec_from_file_location('cka_real_compose_host',root/'host/cka-account-staging-deploy.py')
        module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
        with tempfile.TemporaryDirectory(prefix='cka-compose-policy-') as temp:
            directory=Path(temp);env=directory/'tunnel.env';env.write_text('TUNNEL_TOKEN=synthetic-not-an-operator-credential\n')
            source=(root/'compose.cka-account.staging.yaml').read_text().replace('/etc/shadowops/cka-account-staging/tunnel.env',str(env))
            policy=directory/'compose.yaml';policy.write_text(source)
            digest='sha256:'+'a'*64
            result=subprocess.run(['docker','compose','-p','shadowops-cka-account-staging','-f',str(policy),'config','--format','json'],
                                  env={**os.environ,'CKA_ACCOUNT_IMAGE_DIGEST':digest},capture_output=True,text=True,timeout=20)
            self.assertEqual(result.returncode,0)
            module.compose_policy(json.loads(result.stdout),digest)

    def test_private_identity_reachable_without_default_route_or_instance_metadata(self):
        suffix=secrets.token_hex(6);prefix='cka-account-net-'+suffix
        networks=[prefix+'-idp',prefix+'-origin'];peer=prefix+'-peer';probe=prefix+'-probe'
        def run(*args):
            result=subprocess.run(['docker',*args],capture_output=True,text=True,timeout=120)
            if result.returncode:raise AssertionError('Disposable CKA network operation failed')
            return result.stdout.strip()
        created=[]
        try:
            for network in networks:
                run('network','create','--internal',network);created.append(network)
            run('run','-d','--name',peer,'--read-only','--user','65532:65532','--network',networks[0],
                '--network-alias','id-staging.shadowops.dpdns.org','--entrypoint','python',IMAGE,
                '-m','http.server','9443','--bind','0.0.0.0')
            run('create','--name',probe,'--read-only','--user','65532:65532','--network',networks[1],
                '--entrypoint','python',IMAGE,'-c',PROBE)
            run('network','connect',networks[0],probe)
            self.assertEqual(run('start','-a',probe),'CKA_PRIVATE_NETWORK_PROOF_OK')
        finally:
            # Only names generated by this test are ever removed.
            for name in [probe,peer]:subprocess.run(['docker','rm','-f',name],capture_output=True,timeout=30)
            for network in reversed(created):subprocess.run(['docker','network','rm',network],capture_output=True,timeout=30)

if __name__=='__main__':unittest.main()
