import * as THREE from 'three';
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const portalRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');

// Shared, deterministic GLB2 exporter. Only known, indexed, triangle PBR
// meshes are written. No external textures, base64 data URIs or blobs in Git.
export class GlbSculpture {
  constructor(materials) {
    this.materials=materials;
    this.groups=materials.map(()=>({pos:[],norm:[],uv:[],indices:[]}));
  }
  part(geo,mat=0,loc=[0,0,0],rot=[0,0,0]) {
    const out=this.groups[mat],origin=out.pos.length/3;
    const matrix=new THREE.Matrix4().compose(
      new THREE.Vector3(...loc),
      new THREE.Quaternion().setFromEuler(new THREE.Euler(...rot)),
      new THREE.Vector3(1,1,1)
    );
    const nmat=new THREE.Matrix3().getNormalMatrix(matrix);
    const positions=geo.getAttribute('position'),normals=geo.getAttribute('normal'),uvs=geo.getAttribute('uv');
    const p=new THREE.Vector3(),n=new THREE.Vector3();
    for(let i=0;i<positions.count;i++) {
      p.fromBufferAttribute(positions,i).applyMatrix4(matrix);
      n.fromBufferAttribute(normals,i).applyMatrix3(nmat).normalize();
      out.pos.push(p.x,p.y,p.z);out.norm.push(n.x,n.y,n.z);
      out.uv.push(uvs?.getX(i) ?? 0,uvs?.getY(i) ?? 0);
    }
    if(geo.index) for(let i=0;i<geo.index.count;i++)out.indices.push(origin+geo.index.getX(i));
    else for(let i=0;i<positions.count;i++)out.indices.push(origin+i);
    geo.dispose();
  }
  async write(name,limit=950000) {
    const chunks=[],views=[],accessors=[];
    let offset=0;
    function view(buffer,target) {
      const pad=(4-buffer.length%4)%4;
      chunks.push(buffer,Buffer.alloc(pad));
      const current=offset;offset+=buffer.length+pad;
      return views.push({buffer:0,byteOffset:current,byteLength:buffer.length,target})-1;
    }
    function attr(values,componentType,type,target,dim) {
      const data=componentType===5125?Uint32Array.from(values):Float32Array.from(values);
      const buffer=Buffer.from(data.buffer,data.byteOffset,data.byteLength);
      const entry={bufferView:view(buffer,target),componentType,count:values.length/dim,type};
      if(type==='VEC3'&&target===34962&&componentType===5126) {
        entry.min=[Infinity,Infinity,Infinity];entry.max=[-Infinity,-Infinity,-Infinity];
        for(let i=0;i<values.length;i+=3)for(let j=0;j<3;j++){
          entry.min[j]=Math.min(entry.min[j],values[i+j]);
          entry.max[j]=Math.max(entry.max[j],values[i+j]);
        }
      }
      return accessors.push(entry)-1;
    }
    const primitives=this.groups.map((g,i)=>({
      attributes:{
        POSITION:attr(g.pos,5126,'VEC3',34962,3),
        NORMAL:attr(g.norm,5126,'VEC3',34962,3),
        TEXCOORD_0:attr(g.uv,5126,'VEC2',34962,2),
      },
      indices:attr(g.indices,5125,'SCALAR',34963,1),
      material:i,mode:4,
    }));
    const bin=Buffer.concat(chunks);
    const gltf={
      asset:{version:'2.0',generator:'ShadowOps authored GLB 2.0 sculpture'},
      scene:0,scenes:[{nodes:[0]}],nodes:[{name,mesh:0}],
      meshes:[{name,primitives}],materials:this.materials,
      buffers:[{byteLength:bin.length}],bufferViews:views,accessors,
    };
    const json=Buffer.from(JSON.stringify(gltf));
    const jp=(4-json.length%4)%4,bp=(4-bin.length%4)%4;
    const size=12+8+json.length+jp+8+bin.length+bp;
    if(size>limit)throw Error(name+' exceeds '+limit+' byte GLB budget: '+size);
    const result=Buffer.alloc(size);
    result.writeUInt32LE(0x46546c67,0);
    result.writeUInt32LE(2,4);
    result.writeUInt32LE(size,8);
    result.writeUInt32LE(json.length+jp,12);
    result.writeUInt32LE(0x4e4f534a,16);
    json.copy(result,20);
    result.fill(0x20,20+json.length,20+json.length+jp);
    const binaryOffset=20+json.length+jp;
    result.writeUInt32LE(bin.length+bp,binaryOffset);
    result.writeUInt32LE(0x004e4942,binaryOffset+4);
    bin.copy(result,binaryOffset+8);
    const hash=createHash('sha256').update(result).digest('hex');
    const fileName=name+'-'+hash.slice(0,12)+'.glb';
    await mkdir(path.join(portalRoot,'public','art'),{recursive:true});
    await writeFile(path.join(portalRoot,'public','art',fileName),result);
    const triangles=this.groups.reduce((n,g)=>n+g.indices.length/3,0);
    console.log(name+' GLB: '+size+' bytes, '+triangles+' triangles');
    return {url:'/art/'+fileName,sha256:hash,bytes:size,triangles};
  }
}
export async function writeManifest(name,exports) {
  const lines=['// Generated by ShadowOps original-art build; do not edit.'];
  for(const [key,value] of Object.entries(exports))lines.push('export const '+key+' = '+JSON.stringify(value)+';');
  await writeFile(path.join(portalRoot,'src',name),lines.join('\n')+'\n');
}
